"""Generate the mount's static tables: the maps to offer and the liquid looks.

Inputs are the client's own Map and LiquidType tables already decoded under tools/mount_data/tables
and the catalogue's map list; texture names are resolved to FileDataIDs through the listfile. The mount
reads every geometry and texture from the player's installation; only these small descriptions are compiled in.
Usage: python -B tools/mount_data/generate_mount_tables.py
"""
import json, os, sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'source', 'mount', 'wowforever', 'Runtime', 'Mount', 'Tables.Generated.cs')


def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def argb(v):
    u = v & 0xFFFFFFFF
    return [((u >> 16) & 255) / 255, ((u >> 8) & 255) / 255, (u & 255) / 255]


def main():
    world = json.load(open(os.path.join(ROOT, 'archive', 'converted-assets-2026-10-16', 'wow', 'world.json'), encoding='utf-8'))  # titles and spawn points of the earlier catalogue
    wdts = {m['Id']: m.get('WdtFileDataID') or 0 for m in json.load(open(os.path.join(ROOT, 'tools', 'mount_data', 'maps.json'), encoding='utf-8'))}
    liquids = {r['ID']: r for r in json.load(open(os.path.join(ROOT, 'tools', 'mount_data', 'tables', 'LiquidType.json'), encoding='utf-8'))}
    db = sqlite3.connect(os.path.join(ROOT, 'tools', 'mount_data', 'listfile.sqlite'))
    norm = lambda n: n.replace('%d', '1').replace(chr(92), '/').lower()
    wanted = {norm(t) for r in liquids.values() for t in r['Texture'] if t and not t.startswith('procedural')}
    wanted.add('xtextures/ocean/newoceanbump.blp')
    ids = {}
    for fid, name in db.execute('select id, name from files'):  # one pass: the name column has no index
        n = name.lower()
        if n in wanted:
            ids[n] = int(fid)
    def fdid(name):
        return 0 if not name or name.startswith('procedural') else ids.get(norm(name), 0)
    lines = ['// Generated by tools/mount_data/generate_mount_tables.py. Do not edit.', 'namespace MiniBox.WowForever;', '',
             'internal static class Tables', '{',
             '    public sealed record Map(int Id, string Key, string Directory, string Title, float[] Spawn, uint Wdt);',
             '    public sealed record Liquid(int Id, bool Molten, float[] Shallow, float[] Mid, float[] Deep, float[] Glow, uint Foam, uint Rim, uint Color, uint Emissive);',
             '    public static readonly Map[] Maps =', '    {']
    for c in world['Continents']:
        mid = 0 if c['Id'] == 'eastern_kingdoms' else 1 if c['Id'] == 'kalimdor' else int(c['Id'].split('_')[1])
        spawn = c.get('Spawn')
        sp = 'null' if not spawn else 'new float[] { ' + ', '.join(f'{v:.3f}f' for v in spawn) + ' }'
        lines.append(f'        new({mid}, {cs(c["Id"])}, {cs(c["Directory"])}, {cs(c["Title"])}, {sp}, {wdts.get(c["Id"], 0)}),')
    lines += ['    };', '', '    public static readonly Dictionary<int, Liquid> Liquids = new()', '    {']
    missing = []
    for lid, row in sorted(liquids.items()):
        molten = (row.get('SoundBank') or 0) >= 2
        source = row
        if not molten and row.get('MaterialID') != 130 and liquids.get((row.get('Int') or [0, 0])[1], {}).get('MaterialID') == 130:
            source = liquids[row['Int'][1]]
        tex = source['Texture']
        colors = [argb(v) for v in source['Color']] if source.get('MaterialID') == 130 and any(source.get('Color') or []) else [[0.55, 0.74, 0.70], [0.16, 0.46, 0.54], [0.04, 0.15, 0.22]]
        glow = argb(row['Int'][2]) if (row.get('Int') or [0, 0, 0])[2] > 0xFFFF else argb(row['MinimapStaticCol']) if row.get('MinimapStaticCol') else [1, 0.4, 0]
        foam = fdid(tex[0]); rim = fdid(next((t for t in tex if t and '_rim' in t.lower()), tex[0]))
        color = fdid(tex[0]); emissive = fdid(next((t for t in tex if t and 'emissive' in t.lower()), tex[0]))
        if (molten and not color) or (not molten and not foam):
            missing.append(lid)
        f = lambda v: 'new float[] { ' + ', '.join(f'{x:.4f}f' for x in v) + ' }'
        lines.append(f'        [{lid}] = new({lid}, {str(molten).lower()}, {f(colors[0])}, {f(colors[1])}, {f(colors[2])}, {f(glow)}, {foam}, {rim}, {color}, {emissive}),')
    tables = os.path.join(ROOT, 'tools', 'mount_data', 'tables')
    effects = json.load(open(os.path.join(tables, 'GroundEffectTexture.json'), encoding='utf-8'))
    doodads = json.load(open(os.path.join(tables, 'GroundEffectDoodad.json'), encoding='utf-8'))
    lines += ['    };', '',
              '    public sealed record GroundEffect(int Density, int[] Doodads, int[] Weights);',
              '    public sealed record GroundDoodad(uint Model, float SizeMin, float SizeMax, float RotationMin, float RotationMax);',
              '    public static readonly Dictionary<int, GroundEffect> GroundEffects = new()', '    {']
    for e in effects:
        lines.append(f'        [{e["ID"]}] = new({e["Density"]}, new[] {{ {", ".join(str(x) for x in e["DoodadID"])} }}, new[] {{ {", ".join(str(x) for x in e["DoodadWeight"])} }}),')
    lines += ['    };', '    public static readonly Dictionary<int, GroundDoodad> GroundDoodads = new()', '    {']
    for d in doodads:
        lines.append(f'        [{d["ID"]}] = new({d.get("ModelFileID") or 0}, {d["Size_variation_min"]:.4f}f, {d["Size_variation_max"]:.4f}f, {d["Rotation_variation_min"]:.4f}f, {d["Rotation_variation_max"]:.4f}f),')
    lines += ['    };', '    /// <summary>Ocean bump map used for every water surface (XTextures/ocean/newoceanbump.blp).</summary>',
              f'    public const uint OceanBump = {fdid("XTextures/ocean/newoceanbump.blp")};', '}', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print(json.dumps({'maps': len(world['Continents']), 'liquids': len(liquids), 'liquidsWithoutTexture': missing}))


if __name__ == '__main__':
    main()
